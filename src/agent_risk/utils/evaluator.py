"""Evaluation and benchmark calculation utilities."""

from typing import Any, Dict, List, Union
import numpy as np
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)


def evaluate_risk_predictions(
    y_true: Union[List[int], np.ndarray],
    y_pred: Union[List[int], np.ndarray],
    y_prob: Union[List[float], np.ndarray, None] = None,
) -> Dict[str, Any]:
    """Calculate comprehensive classification metrics for security shield evaluation."""
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    metrics: Dict[str, Any] = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
    }

    if y_prob is not None:
        try:
            metrics["roc_auc"] = float(roc_auc_score(y_true, y_prob))
        except Exception:
            metrics["roc_auc"] = None

    cm = confusion_matrix(y_true, y_pred)
    if cm.shape == (2, 2):
        tn, fp, fn, tp = cm.ravel()
        metrics["confusion_matrix"] = {
            "true_negatives": int(tn),
            "false_positives": int(fp),
            "false_negatives": int(fn),
            "true_positives": int(tp),
        }
        # False Positive Rate (FPR) = FP / (FP + TN)
        metrics["false_positive_rate"] = float(fp / (fp + tn)) if (fp + tn) > 0 else 0.0

    return metrics


def calculate_schema_validity(
    plans: List[Any],
) -> Dict[str, float]:
    """Compute the schema compliance rate for outputs generated by LLM planners."""
    if not plans:
        return {"total": 0, "valid_count": 0, "validity_rate": 0.0}

    valid_count = 0
    for p in plans:
        # Check if plan object has valid non-empty routes and acyclic DAG
        if hasattr(p, "routes") and p.routes:
            try:
                if p.primary_route().is_acyclic():
                    valid_count += 1
            except Exception:
                pass

    return {
        "total": len(plans),
        "valid_count": valid_count,
        "validity_rate": round(valid_count / len(plans), 4),
    }

